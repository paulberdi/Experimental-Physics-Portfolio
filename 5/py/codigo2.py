# Límites físicos razonables
bounds = (
    [-2, 0.001, -0.5, -2],   # mínimos
    [0, 5, 0.5, 0]           # máximos
)

# Ajuste
popt, pcov = curve_fit(v_model, t, v, p0=p0, bounds=bounds, maxfev=50000)
