# Modelo teórico
def v_model(t, vt, tau, t0, v0):
    """Modelo exponencial para velocidad con desplazamiento inicial."""
    return vt - (vt - v0) * np.exp(-(t - t0)/tau)

# Estimaciones iniciales
vt_guess = v[-1]      # velocidad límite (último valor)
v0_guess = v[0]       # valor inicial
tau_guess = (t[-1] - t[0]) / 5
t0_guess = 0
