def accel_from_ts(t, s):
    t = np.asarray(t, dtype=float)
    s = np.asarray(s, dtype=float)
    # sanity checks
    mask = ~np.isnan(t) & ~np.isnan(s)
    t = t[mask]
    s = s[mask]
    if len(t) < 5:
        raise ValueError(f"Se requieren ≥5 puntos para el ajuste, recibidos {len(t)}")
    # ajuste s = p2 t^2 + p1 t + p0
    p2, p1, p0 = np.polyfit(t, s, 2)
    a = 2*p2
    return a, (p2, p1, p0)

